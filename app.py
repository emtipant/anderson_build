def allowed(name):

    return bool(
        name
        and "."
        in name
        and name.rsplit(".", 1)[1].lower()
        in ALLOWED
    )


def save_upload(file):

    """
    Sube la imagen a Supabase Storage
    y devuelve la URL pública.
    """

    if not file:
        return None

    if not file.filename:
        return None

    if not allowed(file.filename):
        return None

    safe_name = secure_filename(file.filename)

    ext = safe_name.rsplit(".", 1)[1].lower()

    filename = f"{uuid.uuid4().hex}.{ext}"

    data = file.read()

    if not data:
        return None

    content_type = (
        mimetypes.guess_type(file.filename)[0]
        or "application/octet-stream"
    )

    try:

        supabase.storage.from_(STORAGE_BUCKET).upload(
            filename,
            data,
            file_options={
                "content-type": content_type,
                "upsert": "false"
            }
        )

        public_url = (
            supabase
            .storage
            .from_(STORAGE_BUCKET)
            .get_public_url(filename)
        )

        return public_url

    except Exception as e:

        print(
            f"ERROR SUBIENDO IMAGEN A SUPABASE: {e}"
        )

        flash(
            "No se pudo subir la imagen a Supabase Storage."
        )

        return None


def storage_path(path):

    if not path:
        return None

    if not isinstance(path, str):
        return None

    marker = (
        f"/storage/v1/object/public/"
        f"{STORAGE_BUCKET}/"
    )

    if marker in path:

        return (
            path
            .split(marker, 1)[1]
            .split("?", 1)[0]
        )

    return None


def save_uploads(files):

    saved = []

    for f in files or []:

        image = save_upload(f)

        if image:
            saved.append(image)

    return saved


def product_gallery(row):

    try:

        gallery = json.loads(
            row["gallery"] or "[]"
        )

        if not isinstance(gallery, list):
            gallery = []

    except (
        TypeError,
        json.JSONDecodeError
    ):

        gallery = []

    main = row["image"]

    return [
        main
    ] + [
        x
        for x in gallery
        if x and x != main
    ]


def delete_local_file(path):

    """
    Mantiene el nombre original de la función.
    Ahora elimina desde Supabase Storage.
    """

    object_path = storage_path(path)

    if not object_path:
        return

    try:

        supabase.storage.from_(
            STORAGE_BUCKET
        ).remove(
            [object_path]
        )

    except Exception as e:

        print(
            "AVISO: no se pudo eliminar "
            f"imagen de Storage: {e}"
        )


