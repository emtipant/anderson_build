def settings_dict(con):

    rows = con.execute(
        "SELECT key,value FROM settings"
    ).fetchall()

    return {
        r["key"]: r["value"]
        for r in rows
    }


def page_data(con):

    pages = con.execute(
        """
        SELECT *
        FROM pages
        WHERE active=1
        ORDER BY sort_order,id
        """
    ).fetchall()

    result = []

    for p in pages:

        d = dict(p)

        d["items"] = [

            dict(x)

            for x in con.execute(
                """
                SELECT *
                FROM page_items
                WHERE page_id=%s
                AND active=1
                ORDER BY sort_order,id
                """,
                (p["id"],)
            ).fetchall()
        ]

        result.append(d)

    return result


